-- Precificação: dados saem da planilha "[Sandstride] Base de Dados – Precificação" e passam a morar no banco.
-- Uma tabela por aba. "linha" mantém a posição que a linha tinha na planilha (o app usa como identificador).
create or replace function public.prec_ok() returns boolean
language sql stable security definer set search_path = public as $$
  select public.eh_admin() or exists (select 1 from public.acessos_apps a where a.usuario_id = auth.uid() and a.app = 'precificacao');
$$;
revoke all on function public.prec_ok() from public, anon;
grant execute on function public.prec_ok() to authenticated;

create table if not exists public.prec_produtos (
  linha bigint primary key generated by default as identity,
  id_produto text, nome text, modelo text, unidades numeric, sku text, custo numeric, embalagem numeric, ativo boolean,
  observacoes text, marca text, modelo_estoque text, composicao text, foto text
);
create table if not exists public.prec_lojas (
  linha bigint primary key generated by default as identity,
  id_loja text, nome text, imposto_pct numeric, atualizado_em text, atualizado_por text, observacoes text
);
create table if not exists public.prec_custos_gerais (
  linha bigint primary key generated by default as identity,
  chave text, nome text, valor numeric, unidade text, atualizado_em text, atualizado_por text, observacoes text
);
create table if not exists public.prec_canais (
  linha bigint primary key generated by default as identity,
  id_canal text, nome text, ativo boolean, imposto_pct numeric, afiliado_pct numeric, comissao_vendedor_pct numeric,
  campanhas_pct numeric, programa_frete_pct numeric, ads_por_pedido numeric, nfe_por_unidade numeric, outros_por_pedido numeric,
  frete_por_pedido numeric, base_da_taxa text, variante_padrao text, taxas_conferidas_em text, fonte text, observacoes text,
  regra_taxa_fixa text, cor text, sigla text, logo text, taxa_pedido numeric, taxa_pedido_nome text
);
create table if not exists public.prec_taxas (
  linha bigint primary key generated by default as identity,
  id_canal text, variante text, preco_min numeric, preco_max numeric, comissao_pct numeric, taxa_fixa numeric, observacoes text
);
create table if not exists public.prec_versoes (
  linha bigint primary key generated by default as identity,
  id_versao text, id_produto text, id_canal text, nome text, status text, preco_venda numeric, variante text, desconto_pct numeric,
  cupom numeric, quantidade numeric, frete numeric, ads numeric, outros_custos numeric, embalagem numeric, reembolso numeric,
  cenario text, lucro_na_criacao numeric, criado_por text, criado_em text, atualizado_em text, observacoes text,
  custo numeric, imposto_pct numeric, afiliado_pct numeric, nfe numeric, ordem numeric
);
create table if not exists public.prec_testes_preco (
  linha bigint primary key generated by default as identity,
  id_teste text, id_produto text, id_canal text, status text, data_inicio text, data_fim text, preco_anterior text, preco_teste text,
  lucro_previsto_unid text, vendas_antes text, vendas_durante text, lucro_real_total text, responsavel text, conclusao text, observacoes text
);
create table if not exists public.prec_historico (
  linha bigint primary key generated by default as identity,
  data_hora text, usuario text, aba text, chave text, campo text, valor_anterior text, valor_novo text, origem text
);
create table if not exists public.prec_sugestoes_taxas (
  linha bigint primary key generated by default as identity,
  id_sugestao text, data text, id_canal text, tabela text, variante text, preco_min text, campo text, valor_atual text,
  valor_sugerido text, fonte text, observacao text, status text
);

do $$ declare t text; begin
  foreach t in array array['prec_produtos','prec_lojas','prec_custos_gerais','prec_canais','prec_taxas','prec_versoes','prec_testes_preco','prec_historico','prec_sugestoes_taxas'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists prec_acesso on public.%I', t);
    execute format('create policy prec_acesso on public.%I for all to authenticated using (public.prec_ok()) with check (public.prec_ok())', t);
  end loop;
end $$;
